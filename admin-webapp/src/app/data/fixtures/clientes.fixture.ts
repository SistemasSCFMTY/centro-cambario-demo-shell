const TIPOS_DOCUMENTO_PF = [
  'Identificación oficial',
  'Comprobante de domicilio',
  'Constancia de situación fiscal',
];
const TIPOS_DOCUMENTO_PM = [
  'Acta constitutiva',
  'Poder del representante legal',
  'Identificación del representante',
  'Constancia de situación fiscal',
];

/** The expediente's files grow with its level: ID at 1, address at 2, the rest at 3. */
function documentosDe(
  id: string,
  tipoPersona: TipoPersona,
  nivel: NivelExpediente,
  fechaAlta: string,
): DocumentoCliente[] {
  const tipos = tipoPersona === 'PM' ? TIPOS_DOCUMENTO_PM : TIPOS_DOCUMENTO_PF;
  const cuantos = tipoPersona === 'PM' ? Math.min(tipos.length, nivel + 1) : nivel;
  return tipos.slice(0, cuantos).map((tipo, i) => ({
    id: `${id}-doc-${i + 1}`,
    tipo,
    nombreArchivo: `${tipo.toLowerCase().replace(/\s+/g, '-')}.pdf`,
    tamanoBytes: 180_000 + i * 64_000,
    fechaDocumento: fechaAlta,
    cotejadoOriginal: i % 2 === 0,
  }));
}

